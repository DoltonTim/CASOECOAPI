-- V1: ESQUEMA RELACIONAL DEL CASO ECORECICLA (ORACLE DATABASE 26ai)
-- Custodia roles, usuarios, puntos de acopio, rutas del dia y pesajes.
-- ============================================================================

CREATE TABLE roles (
    id          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR2(30 CHAR)  NOT NULL,
    descripcion VARCHAR2(150 CHAR),
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT ux_roles_nombre UNIQUE (nombre)
);

CREATE TABLE usuarios (
    id              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    username        VARCHAR2(50 CHAR)  NOT NULL,
    password        VARCHAR2(100 CHAR) NOT NULL,
    nombre_completo VARCHAR2(120 CHAR) NOT NULL,
    estado          BOOLEAN            NOT NULL,
    rol_id          NUMBER(19,0)       NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT ux_usuarios_username UNIQUE (username),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (rol_id) REFERENCES roles (id)
);

CREATE TABLE puntos_acopio (
    id                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    razon_social      VARCHAR2(150 CHAR) NOT NULL,
    direccion         VARCHAR2(200 CHAR) NOT NULL,
    zona              VARCHAR2(50 CHAR)  NOT NULL,
    material_habitual VARCHAR2(80 CHAR)  NOT NULL,
    secuencia         NUMBER(10,0)       NOT NULL,
    activo            BOOLEAN            DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_puntos_acopio PRIMARY KEY (id)
);

CREATE TABLE rutas_dia (
    id                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    codigo            VARCHAR2(30 CHAR) NOT NULL,
    fecha             DATE              NOT NULL,
    zona              VARCHAR2(50 CHAR) NOT NULL,
    estado            VARCHAR2(20 CHAR) NOT NULL,
    operario_username VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT pk_rutas_dia PRIMARY KEY (id),
    CONSTRAINT ux_rutas_dia_codigo UNIQUE (codigo),
    CONSTRAINT ck_rutas_dia_estado CHECK (estado IN ('ABIERTA', 'CERRADA'))
);

CREATE TABLE ruta_puntos (
    id             NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ruta_id        NUMBER(19,0) NOT NULL,
    punto_id       NUMBER(19,0) NOT NULL,
    secuencia      NUMBER(10,0) NOT NULL,
    motivo_omision VARCHAR2(200 CHAR),
    CONSTRAINT pk_ruta_puntos PRIMARY KEY (id),
    CONSTRAINT ux_ruta_punto UNIQUE (ruta_id, punto_id),
    CONSTRAINT fk_rp_ruta FOREIGN KEY (ruta_id) REFERENCES rutas_dia (id),
    CONSTRAINT fk_rp_punto FOREIGN KEY (punto_id) REFERENCES puntos_acopio (id)
);

CREATE TABLE pesajes (
    id               NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    punto_id         NUMBER(19,0)  NOT NULL,
    ruta_id          NUMBER(19,0)  NOT NULL,
    fecha_hora       TIMESTAMP(6)  NOT NULL,
    material         VARCHAR2(80 CHAR) NOT NULL,
    peso_bruto       NUMBER(10,2)  NOT NULL,
    tara             NUMBER(10,2)  NOT NULL,
    peso_neto        NUMBER(10,2)  NOT NULL,
    humedad_estimada NUMBER(5,2)   DEFAULT 0 NOT NULL,
    observacion      VARCHAR2(250 CHAR),
    operario         VARCHAR2(50 CHAR) NOT NULL,
    estado           VARCHAR2(20 CHAR) NOT NULL,
    motivo_anulacion VARCHAR2(250 CHAR),
    CONSTRAINT pk_pesajes PRIMARY KEY (id),
    CONSTRAINT fk_pesajes_punto FOREIGN KEY (punto_id) REFERENCES puntos_acopio (id),
    CONSTRAINT fk_pesajes_ruta FOREIGN KEY (ruta_id) REFERENCES rutas_dia (id),
    CONSTRAINT ck_pesajes_estado CHECK (estado IN ('REGISTRADO', 'ANULADO'))
);
